
-- ExpressMall: PostgreSQL database schema
-- Portfolio 1: Database Design and Modelling
-- Platform: Neon PostgreSQL

CREATE SCHEMA IF NOT EXISTS expressmall;
SET search_path TO expressmall, public;

-- 1. Customers
CREATE TABLE IF NOT EXISTS customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(30),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Brands
CREATE TABLE IF NOT EXISTS brands (
    brand_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_name VARCHAR(120) NOT NULL UNIQUE,
    country_of_origin VARCHAR(100)
);

-- 3. Perfumes
CREATE TABLE IF NOT EXISTS perfumes (
    perfume_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id BIGINT NOT NULL,
    perfume_name VARCHAR(150) NOT NULL,
    scent_type VARCHAR(80),
    size_ml NUMERIC(6,2) NOT NULL CHECK (size_ml > 0),
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    stock_quantity INTEGER NOT NULL DEFAULT 0
        CHECK (stock_quantity >= 0),

    CONSTRAINT fk_perfumes_brand
        FOREIGN KEY (brand_id)
        REFERENCES brands(brand_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT uq_perfume_brand_name_size
        UNIQUE (brand_id, perfume_name, size_ml)
);

-- 4. Customer orders
CREATE TABLE IF NOT EXISTS customer_orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    order_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    order_status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (order_status IN (
            'pending', 'processing', 'shipped',
            'delivered', 'cancelled'
        )),

    CONSTRAINT fk_orders_customer
        FOREIGN KEY (customer_id)
        REFERENCES customers(customer_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- 5. Order items
CREATE TABLE IF NOT EXISTS order_items (
    order_id BIGINT NOT NULL,
    perfume_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),

    CONSTRAINT pk_order_items
        PRIMARY KEY (order_id, perfume_id),

    CONSTRAINT fk_order_items_order
        FOREIGN KEY (order_id)
        REFERENCES customer_orders(order_id)
        ON UPDATE CASCADE ON DELETE CASCADE,

    CONSTRAINT fk_order_items_perfume
        FOREIGN KEY (perfume_id)
        REFERENCES perfumes(perfume_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- 6. Payments
CREATE TABLE IF NOT EXISTS payments (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    payment_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    payment_method VARCHAR(30) NOT NULL
        CHECK (payment_method IN (
            'cash', 'card', 'bank_transfer',
            'mobile_money', 'other'
        )),
    payment_status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (payment_status IN (
            'pending', 'successful', 'failed', 'refunded'
        )),
    transaction_reference VARCHAR(120) UNIQUE,

    CONSTRAINT fk_payments_order
        FOREIGN KEY (order_id)
        REFERENCES customer_orders(order_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_perfumes_brand_id
    ON perfumes(brand_id);

CREATE INDEX IF NOT EXISTS idx_orders_customer_id
    ON customer_orders(customer_id);

CREATE INDEX IF NOT EXISTS idx_orders_order_date
    ON customer_orders(order_date);

CREATE INDEX IF NOT EXISTS idx_order_items_perfume_id
    ON order_items(perfume_id);

CREATE INDEX IF NOT EXISTS idx_payments_order_id
    ON payments(order_id);

CREATE INDEX IF NOT EXISTS idx_payments_status
    ON payments(payment_status);
